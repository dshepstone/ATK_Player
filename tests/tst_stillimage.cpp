void TestStillImage::stepsBackwardToThePreviousIndex()
{
    MediaDecoder decoder;
    QString error;
    QVERIFY2(decoder.open(stillPng(), &error), qPrintable(error));

    // Stepping is index based on the synthesized presentation order, never
    // "time minus one frame": every step back lands on exactly k - 1.
    VideoFrame frame;
    for (int64_t index = 20; index >= 15; --index) {
        QVERIFY(decoder.frameAtIndex(index, frame, &error));
        QCOMPARE(frame.frameIndex, index);
        QCOMPARE(frame.ptsUs, microsecondsAt(index, { 24, 1 }));
    }
}

void TestStillImage::holdsAtRationalRate()
{
    MediaDecoder decoder;
    QString error;
    const ImageSourceOptions hold{ 100, { 24000, 1001 } };
    QVERIFY2(decoder.open(stillPng(), &error, hold), qPrintable(error));

    const MediaMetadata& m = decoder.metadata();
    QCOMPARE(m.frameRate, (FrameRate{ 24000, 1001 }));
    QCOMPARE(m.videoTimeBase.numerator, 1001);
    QCOMPARE(m.videoTimeBase.denominator, 24000);
    QCOMPARE(m.frameCount, int64_t{ 100 });
    QCOMPARE(m.durationUs, microsecondsAt(100, hold.frameRate));
    QCOMPARE(m.durationUs, int64_t{ 4'170'833 });

    VideoFrame frame;
    QVERIFY(decoder.frameAtIndex(99, frame, &error));
    QCOMPARE(frame.ptsTicks, int64_t{ 99 });
    QCOMPARE(frame.ptsUs, microsecondsAt(99, hold.frameRate));
    // ptsTicks in the 1001/24000 time base is the same instant as ptsUs.
    QCOMPARE(atk::media::ffmpeg::ptsToMicroseconds(frame.ptsTicks, AVRational{ 1001, 24000 }),
             frame.ptsUs);
}

