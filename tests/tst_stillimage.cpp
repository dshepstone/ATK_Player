void TestStillImage::frameAtIndexIsExactAndClamps()
{
    MediaDecoder decoder;
    QString error;
    QVERIFY2(decoder.open(stillPng(), &error), qPrintable(error));

    VideoFrame frame;
    QVERIFY(decoder.frameAtIndex(30, frame, &error));
    QCOMPARE(frame.frameIndex, int64_t{ 30 });
    QCOMPARE(frame.ptsTicks, int64_t{ 30 });
    QCOMPARE(decoder.nextFrameIndex(), int64_t{ 31 });

    QVERIFY(decoder.frameAtIndex(-5, frame, &error));
    QCOMPARE(frame.frameIndex, int64_t{ 0 });

    // Past the end answers with the last held frame, like a video that ends
    // before the requested target.
    QVERIFY(decoder.frameAtIndex(1000, frame, &error));
    QCOMPARE(frame.frameIndex, ImageSourceOptions::kDefaultHoldFrames - 1);
    QCOMPARE(decoder.seekOperationCount(), int64_t{ 0 });
}

